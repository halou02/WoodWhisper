/* ============================================================
 * common.js - 全站公共工具函数
 * 人话讲：这里放所有页面都要用的"小工具"，避免每个页面都抄一遍同样的代码。
 * 就像家里的公用剪刀，不用每个房间都买一把，放客厅大家共用。
 *
 * 使用方法：在HTML的</body>前加一行 <script src="js/common.js"></script>
 * 数据从哪来：函数被其他HTML页面的内联<script>调用
 * 数据到哪去：返回处理后的值给调用方
 * ============================================================ */

/* ------------------------------------------------------------
 * escapeHtml(s) - 防XSS攻击的字符转义函数
 * 人话讲：就像寄快递前把"危险物品"标签撕掉换成安全标签。
 *   用户输入的文字里如果藏了 <script> 这种恶意代码，
 *   直接塞进 innerHTML 会被浏览器当代码执行（被攻击）。
 *   这个函数把 < > & " ' 这些特殊字符转换成浏览器不会当代码执行的形式。
 *
 * 参数：s - 要转义的字符串（可能是用户输入、也可能是数据里的文本）
 * 返回：转义后的安全字符串，可以放心放进 innerHTML
 *
 * 新手易错点：
 *   1. 不要对已经转义过的字符串再转义一次，会变成 &amp;lt; 这种乱码
 *   2. 纯文字设置请优先用 textContent，只有需要拼接HTML标签时才用innerHTML+escapeHtml
 *
 * 验证方法：
 *   打开F12控制台输入 escapeHtml('<script>alert(1)</script>')
 *   应该返回 "&lt;script&gt;alert(1)&lt;/script&gt;"，尖括号被转义了
 * ------------------------------------------------------------ */
function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}

/* ------------------------------------------------------------
 * safeColor(color, defaultColor) - CSS颜色安全校验
 * 人话讲：就像门禁保安，只放行穿制服（#RRGGBB格式）的人，
 *   闲杂人等（恶意CSS注入）一律拦下，给个默认色打发走。
 *   颜色要塞进 style="background:..." 里时，必须先过安检，
 *   否则如果数据里是 "red; } body{display:none}" 这种脏字符串，
 *   会污染整个页面的CSS。
 *
 * 参数：
 *   color - 要校验的颜色字符串，比如 "#d4af37"
 *   defaultColor - 可选，校验不通过时返回的默认值，默认是鎏金色 "#d4af37"
 * 返回：合法则返回原颜色，不合法返回默认色
 *
 * 新手易错点：
 *   1. 正则只认 #RRGGBB 6位16进制格式，不支持 red/#rgb/rgba()
 *   2. 简写形式 #fff 也会被拦下，如需支持要改正则为 /^#([0-9A-Fa-f]{3}|[0-9A-Fa-f]{6})$/
 *
 * 验证方法：
 *   safeColor("#d4af37") → "#d4af37"（合法，原样返回）
 *   safeColor("red") → "#d4af37"（不合法，返回默认鎏金色）
 *   safeColor("#fff") → "#d4af37"（3位简写也不合法）
 *   safeColor("") → "#d4af37"
 * ------------------------------------------------------------ */
function safeColor(color, defaultColor) {
  defaultColor = defaultColor || '#d4af37';
  return /^#[0-9A-Fa-f]{6}$/.test(color) ? color : defaultColor;
}
